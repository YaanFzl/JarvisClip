<#
.SYNOPSIS
    Builds the C version of Bufferless into ..\dist\.

.DESCRIPTION
    Uses MSVC (found through vswhere) and links without the C runtime. Produces:

      dist\bufferless-c.exe        unpacked
      dist\bufferless-c-tiny.exe   packed with UPX (skipped with -NoUpx)

    With -Arch x86 it builds a 32-bit version instead (bufferless-c-x86.exe and
    bufferless-c-x86-tiny.exe). It's smaller, but a 32-bit process can only use
    about 3.5 GB, which caps the replay buffer (e.g. 20 minutes at 25+ Mbps
    won't fit).

    Needs Visual Studio's C++ tools and Python (for the icon). The shaders are
    shared with the Rust build (..\shaders\*.cso).

.PARAMETER NoUpx
    Skip the packed build.

.PARAMETER Arch
    x64 (default) or x86.

.PARAMETER Crinkler
    32-bit only, for fun: link with Crinkler (the demoscene's compressing
    linker) instead, producing dist\bufferless-c-x86-crinkler.exe. Crinkler
    can't embed resources, so that exe has no icon in Explorer, and it turns
    on modern control styles at runtime instead of through a manifest. Pass
    the path to Crinkler.exe with -CrinklerPath (or set $env:CRINKLER).
    Antivirus tools flag Crinkler output, so keep it to yourself.
#>
param(
    [switch]$NoUpx,
    [ValidateSet('x64', 'x86')][string]$Arch = 'x64',
    [switch]$Crinkler,
    [string]$CrinklerPath = $env:CRINKLER,
    [int]$HashSize = 16,
    [ValidateSet('INSTANT', 'FAST', 'SLOW', 'VERYSLOW')][string]$CompMode = 'VERYSLOW',
    [string[]]$ExtraCFlags = @(),
    [string[]]$ExtraLinkFlags = @()
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$repo = Split-Path $root -Parent
if ($Crinkler -and $Arch -ne 'x86') { throw 'Crinkler only makes 32-bit executables; add -Arch x86.' }
if ($Crinkler -and -not (Test-Path "$CrinklerPath")) { throw 'Crinkler.exe not found; pass -CrinklerPath.' }
$out = Join-Path $root "build\$Arch$(if ($Crinkler) { '-crinkler' })"
$dist = Join-Path $repo 'dist'
$name = if ($Crinkler) { 'bufferless-c-x86-crinkler' } elseif ($Arch -eq 'x86') { 'bufferless-c-x86' } else { 'bufferless-c' }
New-Item -ItemType Directory -Force $out, $dist | Out-Null

# --- MSVC environment
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw 'Visual Studio with the C++ tools was not found.' }
$env:PATH += ";${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer" # vcvars looks for vswhere
$vcvars = if ($Arch -eq 'x86') { 'vcvars32.bat' } else { 'vcvars64.bat' }
cmd /c "`"$vs\VC\Auxiliary\Build\$vcvars`" >nul && set" | ForEach-Object {
    if ($_ -match '^([^=]+)=(.*)$') { Set-Item "env:$($Matches[1])" $Matches[2] }
}

# --- Generated inputs: shader bytes as a C header, and the icon
$header = "// Generated by build.ps1 from ..\shaders\*.cso. Do not edit.`n"
foreach ($shader in 'cursor_vs', 'cursor_ps') {
    $bytes = [IO.File]::ReadAllBytes((Join-Path $repo "shaders\$shader.cso"))
    $header += "static const unsigned char $shader[] = {" + (($bytes | ForEach-Object { $_ }) -join ',') + "};`n"
}
Set-Content -Encoding ascii (Join-Path $out 'shaders.h') $header

python (Join-Path $root 'tools\make_icon.py') (Join-Path $out 'bufferless.ico')
if ($LASTEXITCODE) { throw 'icon generation failed' }
$manifest = (Join-Path $repo 'bufferless.tiny.manifest') -replace '\\', '\\'
Set-Content -Encoding ascii (Join-Path $out 'bufferless.rc') @"
1 ICON "bufferless.ico"
1 24 "$manifest"
"@
rc /nologo /fo (Join-Path $out 'bufferless.res') (Join-Path $out 'bufferless.rc')
if ($LASTEXITCODE) { throw 'rc failed' }

# --- Compile and link
$version = if ($env:BUFFERLESS_VERSION) { $env:BUFFERLESS_VERSION } else {
    (Select-String -Path (Join-Path $repo 'Cargo.toml') -Pattern '^version = "(.+)"').Matches[0].Groups[1].Value
}
Remove-Item "$out\*.obj" -ErrorAction SilentlyContinue
# Stand-ins for C runtime helpers that compiler-generated code calls; /GL
# can't handle those, so they're compiled separately.
$helpers = 'crt.c', 'crt32.c' | ForEach-Object { Join-Path $root "src\$_" }
$sources = Get-ChildItem (Join-Path $root 'src\*.c') | ForEach-Object FullName | Where-Object { $_ -notin $helpers }
$cflags = @(
    '/nologo', '/c', '/W3', '/O1', '/Os', '/Gy', '/Gw', '/GF', '/GS-', '/Zl', '/std:c17'
    '/DUNICODE', '/D_UNICODE', "/DBUFFERLESS_VERSION=L\`"$version\`"", "/I$out", "/Fo$out\"
)
if ($Crinkler) {
    # Crinkler reads plain object files (no /GL) and can't carry a manifest.
    $cflags += '/DNO_MANIFEST'
    $wholeProgram = @()
} else {
    $wholeProgram = @('/GL')
}
# /Ob1: only inline what's marked inline. Inlining everything costs ~3 KB.
cl @cflags @wholeProgram /Ob1 @ExtraCFlags @sources
if ($LASTEXITCODE) { throw 'compile failed' }
cl @cflags @helpers
if ($LASTEXITCODE) { throw 'compile failed' }

$exe = Join-Path $dist "$name.exe"
$objs = Get-ChildItem "$out\*.obj" | ForEach-Object FullName
$libs = 'kernel32.lib', 'user32.lib', 'gdi32.lib', 'shell32.lib', 'ole32.lib', 'advapi32.lib', 'comctl32.lib',
    'winmm.lib', 'd3d11.lib', 'dxgi.lib', 'mfplat.lib', 'mfuuid.lib', 'dxguid.lib', 'uuid.lib', 'strmiids.lib'
if ($Crinkler) {
    # VERYSLOW only takes ~40 s at this size and beats FAST by ~700 bytes.
    # HASHSIZE is the decompressor's memory in MB, kept until the app exits.
    $crinklerArgs = @(
        '/ENTRY:entry', '/SUBSYSTEM:WINDOWS', '/LARGEADDRESSAWARE', "/COMPMODE:$CompMode", "/HASHSIZE:$HashSize",
        # ole32's COM functions forward to an API set Crinkler can't follow;
        # combase.dll is where they're actually implemented.
        '/NODEFAULTLIB', '/REPLACEDLL:ole32=combase',
        "/REPORT:$out\report.html", "/OUT:$exe"
    ) + $objs + $libs
    & $CrinklerPath @crinklerArgs
    if ($LASTEXITCODE) { throw 'crinkler failed' }
    Write-Host ('{0}: {1:N0} bytes' -f $exe, (Get-Item $exe).Length) -ForegroundColor Green
    return
}
$linkArgs = @(
    '/nologo', '/LTCG', '/NODEFAULTLIB', '/ENTRY:entry', '/SUBSYSTEM:WINDOWS', '/OPT:REF', '/OPT:ICF', '/MANIFEST:NO'
    '/EMITTOOLVERSIONINFO:NO', '/EMITPOGOPHASEINFO', '/DEBUG:NONE', "/MAP:$out\bufferless.map", "/OUT:$exe"
)
if ($Arch -eq 'x86') { $linkArgs += '/LARGEADDRESSAWARE' } # 4 GB instead of 2 GB on 64-bit Windows
$linkArgs += $ExtraLinkFlags + $objs + (Join-Path $out 'bufferless.res') + $libs
link @($linkArgs | Where-Object { $_ })
if ($LASTEXITCODE) { throw 'link failed' }
Write-Host ('{0}: {1:N0} bytes' -f $exe, (Get-Item $exe).Length) -ForegroundColor Green

if (-not $NoUpx) {
    $upx = Get-Command upx -ErrorAction SilentlyContinue
    if (-not $upx) { throw 'UPX not found. Install it with "winget install UPX.UPX", or pass -NoUpx.' }
    $tiny = Join-Path $dist "$name-tiny.exe"
    & $upx.Source --ultra-brute --lzma --quiet --force -o $tiny $exe | Out-Null
    if ($LASTEXITCODE) { throw 'UPX failed' }
    Write-Host ('{0}: {1:N0} bytes' -f $tiny, (Get-Item $tiny).Length) -ForegroundColor Green
}
